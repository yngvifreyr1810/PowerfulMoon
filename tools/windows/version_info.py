"""MIT. One version for the host, updater, installer and candidate pipeline."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
PATTERN = re.compile(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)-powerfulmoon\.([1-9]\d*)")

def version_tuple(value):
    match = PATTERN.fullmatch(value.removeprefix('v'))
    if not match:
        raise ValueError('Unrecognized PowerfulMoon version: ' + value)
    return tuple(map(int, match.groups()))

def metadata(root=ROOT):
    data = json.loads((root / 'release.json').read_text(encoding='utf-8'))
    version_tuple(data['version'])
    if not re.fullmatch(r'v\d+\.\d+\.\d+', data['upstream_tag']):
        raise ValueError('Invalid upstream tag')
    if not re.fullmatch(r'[0-9a-f]{40}', data['upstream_commit']):
        raise ValueError('Invalid upstream commit')
    return data

def generate(root=ROOT):
    data = metadata(root)
    version = data['version']
    (root / 'runtime/release_info.h').write_text(
        '// MIT. Generated by tools/windows/version_info.py; not part of the game-library ABI.\n'
        '#define POWERFULMOON_VERSION "' + version + '"\n', encoding='utf-8')
    resource = root / 'runtime/platform/windows.rc'
    text = resource.read_text(encoding='utf-8')
    nums = ', '.join(map(str, version_tuple(version)))
    text = re.sub(r'(FILEVERSION|PRODUCTVERSION) [\d, ]+', lambda m: m[1] + ' ' + nums, text)
    text = re.sub(r'(VALUE "(?:FileVersion|ProductVersion)", ")[^"]+', lambda m: m[1] + version, text)
    resource.write_text(text, encoding='utf-8')

if __name__ == '__main__':
    generate()
    print(metadata()['version'])
