static inline const OptionNote *option_note(const char *label) {
    for (size_t i = 0; i < sizeof k_option_notes / sizeof *k_option_notes; i++)
        if (!strcmp(k_option_notes[i].label, label)) return &k_option_notes[i];
    return NULL;
}
